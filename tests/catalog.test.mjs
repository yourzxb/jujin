import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readFile,writeFile,cp,rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createApp} from '../server.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const testRoot=path.join(root,'test-results');
test('catalog hot reload accepts a complete pair and retains old catalog on incomplete, invalid or removing updates',async t=>{
 await mkdir(testRoot,{recursive:true});const dir=await mkdtemp(path.join(testRoot,'catalog-'));
 const sourceDir=path.join(dir,'catalog'),dataDir=path.join(dir,'data');await cp(path.join(root,'catalog'),sourceDir,{recursive:true});
 const server=await createApp({sourceDir,dataDir});await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{server.closeAllConnections();await new Promise(r=>server.close(r));assert.equal(path.dirname(dir),testRoot);await rm(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port;
 const state=async()=>{const r=await fetch(base+'/api/state');assert.equal(r.status,200);return r.json();};
 const initial=await state();
 const rfile=path.join(sourceDir,'resource-directory.json'),ifile=path.join(sourceDir,'extra-inspirations.json');
 const resources=JSON.parse(await readFile(rfile,'utf8')),ideas=JSON.parse(await readFile(ifile,'utf8'));
 const bytes=await readFile(path.join(dataDir,'state.json'));
 const addition={...resources.resources[0],id:'cn-hot-reload-test',name:'热更新测试资源',url:'https://github.com/example/catalog-test',repository:'example/catalog-test'};
 resources.resources.push(addition);resources.revision='test-complete-v1';await writeFile(rfile,JSON.stringify(resources));
 assert.equal((await state()).resources.length,initial.resources.length,'half-written catalog must not become visible');
 ideas.revision=resources.revision;await writeFile(ifile,JSON.stringify(ideas));
 assert.equal((await state()).resources.length,initial.resources.length+1);
 const favorite=await fetch(base+'/api/favorites',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({resourceId:addition.id})});assert.equal(favorite.status,200);
 const saved=await readFile(path.join(dataDir,'state.json'));
 ideas.resources.push({id:'cn-incomplete-idea'});resources.revision=ideas.revision='test-invalid-v2';
 await writeFile(rfile,JSON.stringify(resources));await writeFile(ifile,JSON.stringify(ideas));
 assert.equal((await state()).inspirations.length,initial.inspirations.length);
 ideas.resources.pop();resources.resources.pop();resources.revision=ideas.revision='test-removing-v3';
 await writeFile(rfile,JSON.stringify(resources));await writeFile(ifile,JSON.stringify(ideas));
 const retained=await state();assert.ok(retained.favorites.includes(addition.id));assert.equal(retained.resources.length,initial.resources.length+1);
 assert.deepEqual(await readFile(path.join(dataDir,'state.json')),saved,'reload never changes business state');assert.ok(bytes.length>0);
});
